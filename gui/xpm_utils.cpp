QPixmap parse_xpm(const char **xpm_data)
{
  int width, height, colors, charsPerPixel;
  sscanf(xpm_data[0], "%d %d %d %d", &width, &height, &colors, &charsPerPixel);

  QMap<QString, QColor> color_map;
  for (int i = 1; i <= colors; i++)
  {
    QString line(xpm_data[i]);
    /* XPM format: key <whitespace> c <whitespace> color
     * The key is charsPerPixel characters long. */
    QString key = line.left(charsPerPixel);
    /* Find the color definition: skip past "c" and whitespace */
    int cPos = line.indexOf('c');
    if (cPos >= 0)
    {
      QString colorDef = line.mid(cPos + 1).trimmed();
      if (colorDef == "None")
        color_map[key] = Qt::transparent;
      else
        color_map[key] = QColor(colorDef);
    }
  }

  QPixmap pm(width, height);
  pm.fill(Qt::transparent);

  QPainter painter(&pm);
  painter.setCompositionMode(QPainter::CompositionMode_Source);
  for (int y = 0; y < height; y++)
  {
    QString line(xpm_data[1 + colors + y]);
    for (int x = 0; x < width; x++)
    {
      QString ch = line.mid(x * charsPerPixel, charsPerPixel);
      if (color_map.contains(ch))
        painter.fillRect(x, y, 1, 1, color_map[ch]);
    }
  }

  // return pm;

  /* tentative conversion */
  // QImage org_image = pm.toImage();
  // QImage cnv_image = org_image.convertToFormat(QImage::Format_ARGB32);
  // QPixmap final_pm = QPixmap::fromImage(cnv_image);

  QBitmap mask = pm.mask();
  QImage org_image = pm.toImage().convertToFormat(QImage::Format_ARGB32);
  if (!mask.isNull())
  {
    QImage maskImg = mask.toImage();
    for (int y = 0; y < org_image.height(); ++y)
    {
      for (int x = 0; x < org_image.width(); ++x)
      {
        // QBitmap uses color0 (0) as transparent background
        if (maskImg.pixelColor(x, y) == Qt::color0)
        {
          org_image.setPixelColor(x, y, Qt::transparent);
        }
      }
    }
  }

  QPixmap final_pm = QPixmap::fromImage(org_image);

  return final_pm;
}

QIcon loadGdisIcon(const char *embedded_name, const char *disk_name)
{
  for (int i = 0; i < NUM_EMBEDDED; i++)
  {
    if (strcmp(embedded_icons[i].name, embedded_name) == 0)
    {
      /* Return the icon at its original size; let the button handle scaling */
      return QIcon(parse_xpm(embedded_icons[i].data));
    }
  }

  /* Fall back to disk loading */
  QStringList extensions = {".xpm", ".png", ".svg", ".jpg"};
  QString base = QCoreApplication::applicationDirPath();
  QStringList searchPaths = {base + "/", base + "/../src/", base + "/../icons/"};
  for (const QString &base : searchPaths)
  {
    for (const QString &ext : extensions)
    {
      QString path = base + disk_name + ext;
      if (QFile::exists(path))
      {
        QIcon icon(path);
        if (!icon.isNull())
          return icon;
      }
    }
  }

  return QIcon();
}

